// Adapter checks against a real Postgres: error kinds (R1.2), migrations' dialect (R2.1),
// and transaction isolation between concurrent requests (R3.1).
// Run with TICKET_TEST_POSTGRES=postgres://user:pass@host/db.
import assert from "node:assert/strict";
import { connect, dialect, exec, query, script, within_transaction } from "../../src/bindings/db.js";

const url = process.env.TICKET_TEST_POSTGRES;

if (url === undefined || url === "") {
  console.log("skipped: TICKET_TEST_POSTGRES is not set");
  process.exit(0);
}

const text = (value) => ({ $: "SqlText", _0: value });
const int = (value) => ({ $: "SqlInt", _0: value });
const kind = (result) => result.err?.kind ?? "ok";
const must = (result) => {
  assert.ok(result.ok !== undefined, JSON.stringify(result.err));
  return result.ok;
};

must(await connect({ adapter: "postgres", database: url }));
assert.equal(await dialect(), "postgres");

must(await script("DROP SCHEMA public CASCADE; CREATE SCHEMA public"));
must(
  await script(
    `CREATE TABLE "owners" ("id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "name" TEXT NOT NULL UNIQUE);
     CREATE TABLE "pets" ("id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
       "owner_id" BIGINT REFERENCES "owners" ("id"), "age" BIGINT CHECK ("age" >= 0))`,
  ),
);

// R1.2: the same kinds as sqlite
must(await exec(`INSERT INTO "owners" ("name") VALUES (?)`, [text("ada")]));
assert.equal(kind(await exec(`INSERT INTO "owners" ("name") VALUES (?)`, [text("ada")])), "unique");
assert.equal(kind(await exec(`INSERT INTO "owners" ("name") VALUES (NULL)`, [])), "not_null");
assert.equal(kind(await exec(`INSERT INTO "pets" ("owner_id") VALUES (?)`, [int(999)])), "foreign_key");
assert.equal(kind(await exec(`INSERT INTO "pets" ("age") VALUES (?)`, [int(-1)])), "check");
assert.equal(kind(await query("SELEKT 1", [])), "syntax");
assert.equal(kind(await query(`SELECT * FROM "nope"`, [])), "syntax");

// `?` inside quoted text is not a parameter, and COUNT comes back as a number
assert.deepEqual(JSON.parse(must(await query(`SELECT '?' AS q, COUNT(*) AS n FROM "owners" WHERE "name" = ?`, [text("ada")]))), [
  { q: "?", n: 1 },
]);

// transactions: commit, rollback, savepoints
await within_transaction(async () => must(await exec(`INSERT INTO "owners" ("name") VALUES (?)`, [text("grace")])), () => true);
await within_transaction(async () => must(await exec(`INSERT INTO "owners" ("name") VALUES (?)`, [text("gone")])), () => false);
await within_transaction(
  async () => {
    await within_transaction(async () => must(await exec(`INSERT INTO "owners" ("name") VALUES (?)`, [text("inner")])), () => false);
    return true;
  },
  () => true,
);

const names = async () =>
  JSON.parse(must(await query(`SELECT "name" FROM "owners" ORDER BY "name"`, []))).map((row) => row.name);

assert.deepEqual(await names(), ["ada", "grace"]);

// a failed statement inside a savepoint leaves the outer transaction usable
await within_transaction(
  async () => {
    await within_transaction(async () => kind(await exec(`INSERT INTO "owners" ("name") VALUES (?)`, [text("ada")])), () => false);
    must(await exec(`INSERT INTO "owners" ("name") VALUES (?)`, [text("after")]));
  },
  () => true,
);
assert.deepEqual(await names(), ["ada", "after", "grace"]);

// R3.1: another request doesn't see uncommitted rows, and isn't held up by the transaction
let release;
const held = new Promise((resolve) => (release = resolve));
const writer = within_transaction(
  async () => {
    must(await exec(`INSERT INTO "owners" ("name") VALUES (?)`, [text("pending")]));
    await held;
  },
  () => true,
);

await new Promise((resolve) => setTimeout(resolve, 100));
assert.deepEqual(await names(), ["ada", "after", "grace"], "uncommitted row must be invisible");
release();
await writer;
assert.deepEqual(await names(), ["ada", "after", "grace", "pending"]);

// connection errors name the database without its password
const failed = await connect({ adapter: "postgres", database: "postgres://u:secret@127.0.0.1:1/none" });

assert.equal(kind(failed), "connection");
assert.ok(!failed.err.message.includes("secret"), failed.err.message);

console.log("postgres adapter: ok");
process.exit(0);
